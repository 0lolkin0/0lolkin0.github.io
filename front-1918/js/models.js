// ---------- Помощники ----------
const _M = new THREE.Matrix4(), _Q = new THREE.Quaternion(), _E = new THREE.Euler(), _V = new THREE.Vector3(), _S = new THREE.Vector3();
const _up = new THREE.Vector3(0, 1, 0), _dir = new THREE.Vector3();
const mat = (x, y, z, rx = 0, ry = 0, rz = 0, sx = 1, sy = 1, sz = 1) => {
  _E.set(rx, ry, rz, 'YXZ');
  _Q.setFromEuler(_E);
  return _M.compose(_V.set(x, y, z), _Q, _S.set(sx, sy, sz));
};
const CACHE = new Map();
const cached = (key, make) => {
  let g = CACHE.get(key);
  if (!g) { g = make(); if (g.index) g = g.toNonIndexed(); CACHE.set(key, g); }
  return g;
};
// Боковой профиль детали: точки [u, v] (u — вперёд по стволу, v — вверх), ['q', cu, cv, u, v] — плавная кривая.
// Выдавливается на толщину depth по X, со скруглёнными краями
export function profile(pts, depth, bevel = 0.004) {
  return cached('p' + JSON.stringify(pts) + depth + bevel, () => {
    const sh = new THREE.Shape();
    let first = true;
    for (const p of pts) {
      if (p[0] === 'q') sh.quadraticCurveTo(p[1], p[2], p[3], p[4]);
      else if (first) { sh.moveTo(p[0], p[1]); first = false; } else sh.lineTo(p[0], p[1]);
    }
    const d = Math.max(0.001, depth - bevel * 2);
    const g = new THREE.ExtrudeGeometry(sh, { depth: d, bevelEnabled: bevel > 0, bevelThickness: bevel, bevelSize: bevel * 0.8, bevelSegments: 2, curveSegments: 4 });
    g.translate(0, 0, -d / 2);
    g.rotateY(Math.PI / 2);
    return g;
  });
}
// Тело вращения вдоль ствола: точки [r, u]
export function latheZ(pts, seg = 14) {
  return cached('l' + JSON.stringify(pts) + seg, () => {
    const g = new THREE.LatheGeometry(pts.map(([r, u]) => new THREE.Vector2(r, u)), seg);
    g.rotateX(-Math.PI / 2);
    return g;
  });
}
export function lathe(pts, seg = 16) {
  return cached('L' + JSON.stringify(pts) + seg, () => new THREE.LatheGeometry(pts.map(([r, y]) => new THREE.Vector2(r, y)), seg));
}
function capsuleGeo(r, len, seg = 8) {
  return cached('c' + r + '_' + len + '_' + seg, () => new THREE.CapsuleGeometry(r, len, 3, seg));
}
// Капсула между двумя точками
export function capsule(b, ax, ay, az, bx, by, bz, r, color, seg = 8, jitter = 0.03) {
  const dx = bx - ax, dy = by - ay, dz = bz - az, len = Math.hypot(dx, dy, dz);
  _Q.setFromUnitVectors(_up, _dir.set(dx / len, dy / len, dz / len));
  _M.compose(_V.set((ax + bx) / 2, (ay + by) / 2, (az + bz) / 2), _Q, _S.set(1, 1, 1));
  b.add(capsuleGeo(r, Math.max(0.001, len), seg), _M, color, jitter);
}
// Сужающийся цилиндр между двумя точками (руки, ноги): радиус rA у точки a, rB у точки b
const LIMB = {};
export function limb(b, ax, ay, az, bx, by, bz, rA, rB, color, seg = 8) {
  const dx = bx - ax, dy = by - ay, dz = bz - az, len = Math.hypot(dx, dy, dz);
  _Q.setFromUnitVectors(_up, _dir.set(dx / len, dy / len, dz / len));
  const key = seg + '_' + (rB / rA).toFixed(2);
  if (!LIMB[key]) LIMB[key] = new THREE.CylinderGeometry(rB / rA, 1, 1, seg, 1).toNonIndexed();
  _M.compose(_V.set((ax + bx) / 2, (ay + by) / 2, (az + bz) / 2), _Q, _S.set(rA, len, rA));
  b.add(LIMB[key], _M, color, 0.03);
  b.sphere(rB * 0.98, bx, by, bz, color, 1, 1, 1, 1, 0.03);
}

